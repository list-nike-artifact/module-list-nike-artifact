//! AES-256-CTR, replacing the AES-NI `crypto_stream` of `src/aesenc-int.c`.
//!
//! Upstream calls the supercop `aes256ctr/dolbeau/aesenc-int` implementation
//! through an `extern "C"` declaration; it is built from `immintrin.h` and so
//! does not compile for aarch64.  This is the same function, as plain Rust:
//! the 16-byte nonce is a big-endian 128-bit counter, block `i` of the keystream
//! is `AES256_k(nonce + i)`, and the counter's low half is what increments.
//!
//! It is called once per `getnoise`, for `NOISE_BYTES = 2048` bytes, so 128
//! blocks per call and 256 blocks per key generation.  `bench` reports its cost
//! separately; it is far below one percent of key generation either way.

