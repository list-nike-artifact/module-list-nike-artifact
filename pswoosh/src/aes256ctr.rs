const NROUNDS: usize = 14;

/* xtime, multiplication by X in GF(2^8) */
fn xt(a: u8) -> u8 {
    (a << 1) ^ (0x1b & (0u8.wrapping_sub(a >> 7)))
}

/* AES-256 key schedule: 15 round keys of 16 bytes */
fn key_expand(key: &[u8; 32]) -> [[u8; 16]; NROUNDS+1] {
    let mut w = [[0u8; 4]; 4*(NROUNDS+1)];
    for i in 0..8 {
        w[i].copy_from_slice(&key[4*i..4*i+4]);
    }
    let mut rcon: u8 = 1;
    for i in 8..4*(NROUNDS+1) {
        let mut t = w[i-1];
        if i % 8 == 0 {
            t = [SBOX[t[1] as usize] ^ rcon, SBOX[t[2] as usize],
                 SBOX[t[3] as usize], SBOX[t[0] as usize]];
            rcon = xt(rcon);
        } else if i % 8 == 4 {
            t = [SBOX[t[0] as usize], SBOX[t[1] as usize],
                 SBOX[t[2] as usize], SBOX[t[3] as usize]];
        }
        for j in 0..4 {
            w[i][j] = w[i-8][j] ^ t[j];
        }
    }

    let mut rk = [[0u8; 16]; NROUNDS+1];
    for r in 0..NROUNDS+1 {
        for c in 0..4 {
            rk[r][4*c..4*c+4].copy_from_slice(&w[4*r+c]);
        }
    }
    rk
}

/* One AES-256 block encryption, out = AES256_rk(inp) */
fn encrypt_block(out: &mut [u8; 16], inp: &[u8; 16], rk: &[[u8; 16]; NROUNDS+1]) {
    let mut s = *inp;
    for i in 0..16 {
        s[i] ^= rk[0][i];
    }

    for r in 1..NROUNDS+1 {
        /* SubBytes */
        for i in 0..16 {
            s[i] = SBOX[s[i] as usize];
        }
        /* ShiftRows: byte 4c+r of the state is row r, column c */
        let t = s;
        for c in 0..4 {
            for r2 in 0..4 {
                s[4*c + r2] = t[4*((c + r2) % 4) + r2];
            }
        }
        /* MixColumns, skipped in the last round */
        if r != NROUNDS {
            for c in 0..4 {
                let a = [s[4*c], s[4*c+1], s[4*c+2], s[4*c+3]];
                let x = a[0] ^ a[1] ^ a[2] ^ a[3];
                for i in 0..4 {
                    s[4*c+i] = a[i] ^ x ^ xt(a[i] ^ a[(i+1) % 4]);
                }
            }
        }
        /* AddRoundKey */
        for i in 0..16 {
            s[i] ^= rk[r][i];
        }
    }

    *out = s;
}

/// `out = AES256-CTR_k(n)`, with `n` the initial value of a big-endian 128-bit
/// counter.  Matches `crypto_stream` of `aesenc-int.c`.
pub fn crypto_stream(out: &mut [u8], n: &[u8; 16], k: &[u8; 32]) {
    let rk = key_expand(k);
    let hi = u64::from_be_bytes(n[0..8].try_into().unwrap());
    let lo = u64::from_be_bytes(n[8..16].try_into().unwrap());
    let mut ctr = ((hi as u128) << 64) | (lo as u128);

    let mut blk = [0u8; 16];
    let mut i = 0usize;
    while i < out.len() {
        let inp = ctr.to_be_bytes();
        encrypt_block(&mut blk, &inp, &rk);
        let take = core::cmp::min(16, out.len() - i);
        out[i..i+take].copy_from_slice(&blk[..take]);
        ctr = ctr.wrapping_add(1);
        i += 16;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /* FIPS-197 C.3, AES-256 of 00112233..eeff under key 000102..1f */
    #[test]
    fn test_aes256_kat() {
        let mut key = [0u8; 32];
        for i in 0..32 {
            key[i] = i as u8;
        }
        let mut inp = [0u8; 16];
        for i in 0..16 {
            inp[i] = (0x11 * i) as u8;
        }
        let want: [u8; 16] = [0x8e,0xa2,0xb7,0xca,0x51,0x67,0x45,0xbf,
                              0xea,0xfc,0x49,0x90,0x4b,0x49,0x60,0x89];
        let rk = key_expand(&key);
        let mut got = [0u8; 16];
        encrypt_block(&mut got, &inp, &rk);
        assert_eq!(got, want, "AES-256 does not match FIPS-197 C.3");
    }

    /* SP 800-38A F.5.5, AES-256-CTR keystream */
    #[test]
    fn test_aes256ctr_kat() {
        let key: [u8; 32] = [
            0x60,0x3d,0xeb,0x10,0x15,0xca,0x71,0xbe,0x2b,0x73,0xae,0xf0,0x85,0x7d,0x77,0x81,
            0x1f,0x35,0x2c,0x07,0x3b,0x61,0x08,0xd7,0x2d,0x98,0x10,0xa3,0x09,0x14,0xdf,0xf4];
        let n: [u8; 16] = [0xf0,0xf1,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,
                           0xf8,0xf9,0xfa,0xfb,0xfc,0xfd,0xfe,0xff];
        /* plaintext XOR ciphertext of the first block of the test vector */
        let want: [u8; 16] = [0x0b,0xdf,0x7d,0xf1,0x59,0x17,0x16,0x33,
                              0x5e,0x9a,0x8b,0x15,0xc8,0x60,0xc5,0x02];
        let mut ks = [0u8; 16];
        crypto_stream(&mut ks, &n, &key);
        assert_eq!(ks, want, "AES-256-CTR keystream does not match SP 800-38A F.5.5");
    }
}
